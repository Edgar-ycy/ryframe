use super::{History, Version};
use crate::ResourceIr;

pub(super) fn incremental(resource: &ResourceIr, id: &str, statements: &[String]) -> String {
    let sql = statements
        .iter()
        .map(|sql| format!("    {sql:?},"))
        .collect::<Vec<_>>()
        .join("\n");
    let has_escape = statements
        .iter()
        .any(|statement| statement.contains("\\\\"));
    let connection_import = if has_escape {
        "DbBackend"
    } else {
        "ConnectionTrait, DbBackend"
    };
    let execute = if has_escape {
        "            ryframe_sdk::execute_generated_mysql_ddl(manager.get_connection(), statement).await?;"
    } else {
        "            manager.get_connection().execute_unprepared(statement).await?;"
    };
    format!(
        r#"// @generated by RyFrame {generator}
// resource: {name}
// schema-sha256: {hash}
// 请勿手工修改；审阅后显式执行向前迁移。

use ryframe_sdk::persistence::sea_orm::{{{connection_import}}};
use ryframe_sdk::persistence::sea_orm_migration::prelude::*;

pub const MIGRATION_NAME: &str = {id:?};
pub const DDL: &[&str] = &[
{sql}
];

pub struct Migration;

impl MigrationName for Migration {{
    fn name(&self) -> &str {{ MIGRATION_NAME }}
}}

#[ryframe_sdk::async_trait]
impl MigrationTrait for Migration {{
    async fn up(&self, manager: &SchemaManager) -> Result<(), DbErr> {{
        if manager.get_database_backend() != DbBackend::MySql {{
            return Err(DbErr::Custom("业务增量迁移只支持 MySQL".into()));
        }}
        for statement in DDL {{
{execute}
        }}
        Ok(())
    }}

    async fn down(&self, _manager: &SchemaManager) -> Result<(), DbErr> {{
        Err(DbErr::Custom("业务迁移只允许追加与向前修复，禁止 down".into()))
    }}
}}
"#,
        generator = crate::GENERATOR_VERSION,
        name = resource.name,
        hash = resource.schema_hash
    )
}

pub(in crate::business) fn registry(module: &str, history: &History) -> String {
    let mut declarations = Vec::new();
    let mut entries = Vec::new();
    for resource in &history.resources {
        for (index, version) in resource.versions.iter().enumerate() {
            let id = &version.id;
            declarations.push(format!(
                "#[path = \"../../../migrations/{id}.rs\"]\nmod {id};"
            ));
            if index == 0 {
                declarations.push(format!(
                    "const _: () = assert!({id}::INITIAL_RESOURCE_MIGRATION);"
                ));
            }
            entries.push(entry(
                module,
                &resource.descriptor.table,
                resource.descriptor.database,
                version,
                index
                    .checked_sub(1)
                    .map(|previous| &resource.versions[previous]),
            ));
        }
    }
    format!(
        "// @generated by RyFrame {}\n// 请勿手工修改。\n\n{}\n\npub fn migrations() -> Vec<std::sync::Arc<dyn ryframe_sdk::BusinessMigration>> {{\n    vec![\n{}\n    ]\n}}\n",
        crate::GENERATOR_VERSION,
        declarations.join("\n"),
        entries.join("\n")
    )
}

fn entry(
    module: &str,
    table: &str,
    database: super::super::OwnedResourceDatabase,
    version: &Version,
    before: Option<&Version>,
) -> String {
    let id = &version.id;
    let scope = match database {
        super::super::OwnedResourceDatabase::Control => "Control",
        super::super::OwnedResourceDatabase::Tenant => "Tenant",
    };
    let fingerprint = before.map_or_else(
        || "None".into(),
        |previous| format!("Some({:?})", previous.schema_hash),
    );
    let canonical = before.map_or_else(
        || "None".into(),
        |previous| format!("Some({:?})", previous.canonical),
    );
    let sql = if before.is_some() {
        format!("{id}::DDL")
    } else {
        format!("&[{id}::CREATE_TABLE_DDL]")
    };
    format!(
        "        std::sync::Arc::new(ryframe_sdk::SeaOrmBusinessMigration::new({module:?}, {id:?}, {:?}, ryframe_sdk::BusinessMigrationSchema {{ before_fingerprint: {fingerprint}, after_fingerprint: {:?}, tables: &[ryframe_sdk::BusinessTableSchema {{ table: {table:?}, before: {canonical}, after: {:?} }}] }}, ryframe_sdk::BusinessMigrationScope::{scope}, {id}::Migration).with_initialization_sql({sql})),",
        version.checksum, version.schema_hash, version.canonical
    )
}
