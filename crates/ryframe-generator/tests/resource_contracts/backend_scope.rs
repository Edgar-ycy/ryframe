#[cfg(windows)]
#[test]
fn backend_updates_do_not_open_or_replace_exclusively_locked_frontend_files() {
    use std::os::windows::fs::OpenOptionsExt;

    let mut resources = order();
    let (workspace, _, frontend) = install(&resources);
    let frontend_before = snapshot(&workspace.frontend);
    let locks = frontend
        .iter()
        .map(|entry| {
            fs::OpenOptions::new()
                .read(true)
                .share_mode(0)
                .open(workspace.frontend.join(&entry.path))
                .unwrap()
        })
        .collect::<Vec<_>>();
    for entry in &frontend {
        assert!(
            fs::read(workspace.frontend.join(&entry.path)).is_err(),
            "独占句柄必须阻止其他读取，才能证明后续后端调用未打开前端文件"
        );
    }
    resources[0].source_hash = "a".repeat(64);
    resources[0].labels.zh_cn = "独占文件范围测试设备".into();
    let changed = backend_catalog(&resources);
    let scope = workspace.scope(true);
    assert_backend_plan(&plan_all_resource_changes(&changed, scope).unwrap());
    assert_backend_plan(&plan_resource_changes(&changed, "order", scope).unwrap());
    let desired = plan_resource_assets(&changed, "order", scope).unwrap();
    assert!(desired.iter().all(|asset| asset.root == AssetRoot::Backend));
    let report = write_resources(&changed, scope).unwrap();
    assert!(!report.updated.is_empty());
    assert_backend_report(&report);
    assert_backend_report(&write_resource(&changed, "order", scope).unwrap());
    assert_eq!(workspace.frontend_entries(), frontend);
    drop(locks);
    assert_eq!(snapshot(&workspace.frontend), frontend_before);
    assert_zero_diff(&changed, scope);
}
