#[test]
fn named_update_preserves_other_backend_assets_and_stale_frontend_metadata() {
    let mut resources = post_and_notice();
    let (workspace, _, frontend) = install(&resources);
    let notice_entries = workspace
        .manifest()
        .entries
        .into_iter()
        .filter(|entry| entry.root == AssetRoot::Backend && entry.resource == "notice")
        .collect::<Vec<_>>();
    assert!(!notice_entries.is_empty());
    let notice_files = notice_entries
        .iter()
        .map(|entry| {
            (
                entry.path.clone(),
                fs::read(workspace.backend.join(&entry.path)).unwrap(),
            )
        })
        .collect::<BTreeMap<_, _>>();
    remove_frontend_files(&workspace, &frontend);
    resources[0].source_hash = "d".repeat(64);
    resources[0].labels.zh_cn = "范围测试岗位".into();
    resources[0].menu.labels.zh_cn = "范围测试岗位管理".into();
    let changed = backend_catalog(&resources);
    let before = snapshot(&workspace.backend);
    let scope = workspace.scope(false);
    let desired = plan_resource_assets(&changed, "post", scope).unwrap();
    assert!(!desired.is_empty());
    assert!(desired.iter().all(|asset| asset.root == AssetRoot::Backend
        && matches!(asset.resource.as_str(), "post" | "__catalog__")));
    let plan = plan_resource_changes(&changed, "post", scope).unwrap();
    assert_backend_plan(&plan);
    assert!(plan.assets.iter().all(|asset| asset.resource != "notice"));
    let expected = planned_manifest(&plan);
    assert_eq!(snapshot(&workspace.backend), before);
    let report = write_resource(&changed, "post", scope).unwrap();
    assert_backend_report(&report);
    assert!(!report.updated.is_empty());
    assert_eq!(workspace.manifest().entries, expected.entries);
    assert_eq!(workspace.frontend_entries(), frontend);
    assert_eq!(
        workspace
            .manifest()
            .entries
            .into_iter()
            .filter(|entry| entry.root == AssetRoot::Backend && entry.resource == "notice")
            .collect::<Vec<_>>(),
        notice_entries
    );
    for (path, bytes) in notice_files {
        assert_eq!(fs::read(workspace.backend.join(path)).unwrap(), bytes);
    }
    let unchanged = snapshot(&workspace.backend);
    // 此时 Post 的后端来源哈希已前进，旧前端哈希不得污染未选中资源的核验。
    for selected in ["post", "notice"] {
        let plan = plan_resource_changes(&changed, selected, scope).unwrap();
        assert_backend_plan(&plan);
        assert!(
            plan.assets
                .iter()
                .all(|asset| asset.action == PlanAction::Unchanged)
        );
        let report = write_resource(&changed, selected, scope).unwrap();
        assert_backend_report(&report);
        assert!(report.written.is_empty() && report.removed.is_empty());
        assert_eq!(snapshot(&workspace.backend), unchanged);
    }
    assert_zero_diff(&changed, scope);
    assert_eq!(workspace.frontend_entries(), frontend);
    assert!(snapshot(&workspace.frontend).is_empty());
}

