#[test]
fn source_hash_metadata_can_advance_independently_of_historical_frontend() {
    let mut resources = order();
    let (workspace, original, frontend) = install(&resources);
    remove_frontend_files(&workspace, &frontend);
    resources[0].source_hash = "b".repeat(64);
    assert_ne!(resources[0].source_hash, frontend[0].source_hash);
    let changed = backend_catalog(&resources);
    assert_eq!(
        changed.assets, original.assets,
        "仅来源哈希变化不得改写产品源码"
    );
    let before = snapshot(&workspace.backend);
    let plan = plan_all_resource_changes(&changed, workspace.scope(false)).unwrap();
    assert_backend_plan(&plan);
    let mutations = plan
        .assets
        .iter()
        .filter(|asset| asset.action != PlanAction::Unchanged)
        .collect::<Vec<_>>();
    assert_eq!(mutations.len(), 1);
    assert_eq!(mutations[0].path, OWNERSHIP_PATH);
    let expected = planned_manifest(&plan);
    assert_eq!(
        expected
            .entries
            .iter()
            .filter(|entry| entry.root == AssetRoot::Frontend)
            .cloned()
            .collect::<Vec<_>>(),
        frontend
    );
    assert_eq!(
        snapshot(&workspace.backend),
        before,
        "预览不得推进 manifest"
    );
    let report = write_resources(&changed, workspace.scope(false)).unwrap();
    assert_backend_report(&report);
    assert_eq!(workspace.manifest().entries, expected.entries);
    assert!(
        workspace
            .manifest()
            .entries
            .iter()
            .filter(|entry| entry.root == AssetRoot::Backend && entry.resource == "order")
            .all(|entry| entry.source_hash == resources[0].source_hash)
    );
    let after = snapshot(&workspace.backend);
    assert_ne!(
        after[Path::new(OWNERSHIP_PATH)],
        before[Path::new(OWNERSHIP_PATH)]
    );
    for (path, bytes) in before
        .iter()
        .filter(|(path, _)| path.as_path() != Path::new(OWNERSHIP_PATH))
    {
        assert_eq!(&after[path], bytes);
    }
    assert_zero_diff(&changed, workspace.scope(false));
    assert_eq!(workspace.frontend_entries(), frontend);
    assert!(snapshot(&workspace.frontend).is_empty());
}

