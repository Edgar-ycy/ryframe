use std::{
    collections::{BTreeMap, BTreeSet},
    fs,
    path::{Path, PathBuf},
};

use ryframe_generator::{
    AssetRoot, GeneratedAsset, GeneratedCatalog, OwnershipEntry, OwnershipManifest, PlanAction,
    ResourceAssetPlan, ResourceError, ResourceIr, ResourceWorkspace, SafeWriteReport,
    load_resource, plan_all_resource_changes, plan_resource_assets, plan_resource_changes,
    render_resources, write_resource, write_resources,
};

const OWNERSHIP_PATH: &str = "catalog/resources/.ownership.toml";

struct Workspace {
    _directory: tempfile::TempDir,
    backend: PathBuf,
    frontend: PathBuf,
}

impl Workspace {
    fn new() -> Self {
        let base = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../.local-tests/backend-scope");
        fs::create_dir_all(&base).expect("应创建后端范围测试的隔离根目录");
        let directory = tempfile::Builder::new()
            .prefix("case-")
            .tempdir_in(base)
            .expect("应创建唯一测试目录");
        let backend = directory.path().join("backend");
        let frontend = directory.path().join("frontend");
        fs::create_dir(&backend).unwrap();
        fs::create_dir(&frontend).unwrap();
        // 隔离夹具启用稳定版保护，不依赖外部仓库历史，也不放宽迁移检查。
        fs::write(
            backend.join("Cargo.toml"),
            "[workspace.package]\nversion = \"1.0.0\"\n",
        )
        .unwrap();
        Self {
            _directory: directory,
            backend,
            frontend,
        }
    }

    fn scope(&self, frontend: bool) -> ResourceWorkspace<'_> {
        ResourceWorkspace {
            backend_root: &self.backend,
            frontend_root: frontend.then_some(self.frontend.as_path()),
        }
    }

    fn manifest(&self) -> OwnershipManifest {
        toml::from_str(&fs::read_to_string(self.backend.join(OWNERSHIP_PATH)).unwrap()).unwrap()
    }

    fn frontend_entries(&self) -> Vec<OwnershipEntry> {
        self.manifest()
            .entries
            .into_iter()
            .filter(|entry| entry.root == AssetRoot::Frontend)
            .collect()
    }
}

fn order() -> Vec<ResourceIr> {
    vec![
        load_resource(Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/order.toml"))
            .expect("Order 夹具应有效"),
    ]
}

fn post_and_notice() -> Vec<ResourceIr> {
    ["post", "notice"]
        .into_iter()
        .map(|name| {
            load_resource(
                Path::new(env!("CARGO_MANIFEST_DIR"))
                    .join(format!("../../catalog/resources/{name}.toml")),
            )
            .expect("Post 和 Notice 生产清单应有效")
        })
        .collect()
}

fn backend_catalog(resources: &[ResourceIr]) -> GeneratedCatalog {
    let catalog = render_resources(resources).expect("离线 Rust 后端生成应成功");
    assert!(!catalog.assets.is_empty());
    assert!(
        catalog
            .assets
            .iter()
            .all(|asset| asset.root == AssetRoot::Backend),
        "默认生成不得隐式请求前端资产"
    );
    catalog
}

fn with_frontend(mut catalog: GeneratedCatalog) -> GeneratedCatalog {
    let names = catalog
        .assets
        .iter()
        .map(|asset| asset.resource.clone())
        .collect::<BTreeSet<_>>();
    for name in names {
        let path = if name == "__catalog__" {
            "src/generated/resources/index.ts".into()
        } else {
            format!("src/generated/resources/{name}/scope_placeholder.ts")
        };
        catalog.assets.push(GeneratedAsset {
            resource: name.clone(),
            root: AssetRoot::Frontend,
            path,
            content: format!(
                "// @generated by RyFrame {}\n// resource: {name}\n// 历史 ownership 范围测试占位，仅包含注释。\n",
                ryframe_generator::GENERATOR_VERSION,
            ),
        });
    }
    catalog
}

fn install(resources: &[ResourceIr]) -> (Workspace, GeneratedCatalog, Vec<OwnershipEntry>) {
    let workspace = Workspace::new();
    let backend = backend_catalog(resources);
    write_resources(&with_frontend(backend.clone()), workspace.scope(true))
        .expect("首次应写入后端资产与历史前端占位资产");
    let frontend = workspace.frontend_entries();
    assert_eq!(frontend.len(), resources.len() + 1);
    assert!(
        frontend
            .iter()
            .all(|entry| workspace.frontend.join(&entry.path).is_file())
    );
    (workspace, backend, frontend)
}

fn snapshot(root: &Path) -> BTreeMap<PathBuf, Vec<u8>> {
    fn visit(root: &Path, directory: &Path, files: &mut BTreeMap<PathBuf, Vec<u8>>) {
        for entry in fs::read_dir(directory).unwrap() {
            let entry = entry.unwrap();
            let kind = entry.file_type().unwrap();
            assert!(!kind.is_symlink(), "隔离测试目录不得包含符号链接");
            if kind.is_dir() {
                visit(root, &entry.path(), files);
            } else {
                files.insert(
                    entry.path().strip_prefix(root).unwrap().to_owned(),
                    fs::read(entry.path()).unwrap(),
                );
            }
        }
    }
    let mut files = BTreeMap::new();
    visit(root, root, &mut files);
    files
}

fn remove_frontend_files(workspace: &Workspace, entries: &[OwnershipEntry]) {
    for entry in entries {
        fs::remove_file(workspace.frontend.join(&entry.path)).unwrap();
    }
    assert!(snapshot(&workspace.frontend).is_empty());
}

fn assert_backend_plan(plan: &ResourceAssetPlan) {
    assert!(!plan.assets.is_empty());
    assert!(
        plan.assets
            .iter()
            .all(|asset| asset.root == AssetRoot::Backend)
    );
}

fn assert_backend_report(report: &SafeWriteReport) {
    for paths in [
        &report.created,
        &report.updated,
        &report.written,
        &report.removed,
        &report.unchanged,
    ] {
        assert!(
            paths.iter().all(|path| path.starts_with("backend:")),
            "{report:?}"
        );
    }
}

fn assert_zero_diff(catalog: &GeneratedCatalog, workspace: ResourceWorkspace<'_>) {
    let before = snapshot(workspace.backend_root);
    let plan = plan_all_resource_changes(catalog, workspace).expect("重复生成的全量计划应成功");
    assert_backend_plan(&plan);
    assert!(
        plan.assets
            .iter()
            .all(|asset| asset.action == PlanAction::Unchanged)
    );
    let report = write_resources(catalog, workspace).expect("重复写入应成功");
    assert_backend_report(&report);
    assert!(
        report.created.is_empty()
            && report.updated.is_empty()
            && report.written.is_empty()
            && report.removed.is_empty()
    );
    assert_eq!(snapshot(workspace.backend_root), before);
}

fn planned_manifest(plan: &ResourceAssetPlan) -> OwnershipManifest {
    let asset = plan
        .assets
        .iter()
        .find(|asset| asset.path == OWNERSHIP_PATH)
        .expect("元数据变化必须进入 ownership 预览");
    assert_eq!(asset.root, AssetRoot::Backend);
    assert_eq!(asset.action, PlanAction::Update);
    toml::from_str(&asset.after).unwrap()
}

fn assert_error(error: ResourceError, message: &str) {
    assert!(error.message.contains(message), "{error}");
    assert!(!error.suggestion.is_empty(), "失败关闭必须提供修复建议");
}

fn assert_all_reject(
    workspace: &Workspace,
    catalog: &GeneratedCatalog,
    selected: &str,
    frontend: bool,
    message: &str,
) {
    let backend_before = snapshot(&workspace.backend);
    let frontend_before = snapshot(&workspace.frontend);
    let scope = workspace.scope(frontend);
    assert_error(
        plan_all_resource_changes(catalog, scope).expect_err("全量预览应失败关闭"),
        message,
    );
    assert_error(
        plan_resource_assets(catalog, selected, scope).expect_err("命名资产预览应失败关闭"),
        message,
    );
    assert_error(
        plan_resource_changes(catalog, selected, scope).expect_err("命名变更预览应失败关闭"),
        message,
    );
    assert_error(
        write_resources(catalog, scope).expect_err("全量写入应失败关闭"),
        message,
    );
    assert_error(
        write_resource(catalog, selected, scope).expect_err("命名写入应失败关闭"),
        message,
    );
    assert_eq!(snapshot(&workspace.backend), backend_before);
    assert_eq!(snapshot(&workspace.frontend), frontend_before);
}

